function closeEnough(a: readonly number[], b: readonly number[]): boolean {
  return a.every((v, i) => Math.abs(v - b[i]) <= 16);
}

describe('decodePickedImage', () => {
  test('decodes a JPEG sheet and imports it, within tolerance', () => {
    const image = decodePickedImage('image/jpeg', SHEET_JPEG_BASE64);
    expect(image.width).toBe(1280);
    expect(image.height).toBe(320);
    const imported = importSpriteSheet(image);
    expect(imported.name).toBe('POKEMON GO');
    expect(imported.items).toHaveLength(3);
    // JPEG is lossy, so tiles are close, not exact:
    // flat colour centres should be within a few steps.
    expect(closeEnough(imported.items[0][0], [255, 0, 0])).toBe(true);
    expect(closeEnough(imported.items[1][0], [0, 255, 0])).toBe(true);
    expect(closeEnough(imported.items[2][0], [0, 0, 255])).toBe(true);
  });

  test('PNG still decodes, other mimes throw plainly', () => {
    const png = base64js.toByteArray(
      'iVBORw0KGgoAAAANSUhEUgAAAAQAAAACCAIAAADwyuo0AAAAGklEQVR4nDXEsQEAAAjDIE7v53GSASHU3zYcihcKeBGtKckAAAAASUVORK5CYII=',
    );
    const image = decodePickedImage(
      'image/png',
      base64js.fromByteArray(png),
    );
    expect(image.width).toBe(4);
    expect(image.height).toBe(2);
    expect(() => decodePickedImage('image/heic', 'AAAA')).toThrow(
      'Picked file is image/heic; only PNG and JPEG',
    );
  });
});
